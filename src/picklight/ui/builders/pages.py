"""Build the pages region."""

from __future__ import annotations

from PySide6.QtCore import QSize, QTimer, Qt
from PySide6.QtGui import QColor, QIcon, QPixmap
from PySide6.QtWidgets import (
    QGridLayout,
    QHBoxLayout,
    QListWidget,
    QPushButton,
    QSizePolicy,
    QStackedWidget,
    QVBoxLayout,
    QWidget,
)

from picklight.paths import asset_path
from picklight.ui.common import label
from picklight.ui.folders import FolderSectionToggle
from picklight.ui.gallery import EmptyFolderIllustration, PhotoGrid, PhotoGridDelegate, PhotoGridHeader
from picklight.viewer import LoupeCanvas
from picklight.ui.review_feedback import ReviewFeedback


def build_pages(self, viewer_layout):
    self.center_stack = QStackedWidget()
    self.filmstrip = PhotoGrid()
    self.filmstrip.setObjectName("photoGrid")
    self.filmstrip.setViewMode(QListWidget.ViewMode.IconMode)
    photo_delegate = PhotoGridDelegate(self.filmstrip)
    photo_delegate.renameRequested.connect(self._commit_photo_rename)
    self.filmstrip.setItemDelegate(photo_delegate)
    self.filmstrip.setEditTriggers(QListWidget.EditTrigger.NoEditTriggers)
    self.filmstrip.setFlow(QListWidget.Flow.TopToBottom)
    self.filmstrip.setMovement(QListWidget.Movement.Free)
    self.filmstrip.setResizeMode(QListWidget.ResizeMode.Fixed)
    self.thumbnail_size = QSize(185, 123)
    self.filmstrip.setIconSize(self.thumbnail_size)
    self.filmstrip.setGridSize(QSize())
    self.filmstrip.setWrapping(False)
    self.filmstrip.setUniformItemSizes(False)
    self.filmstrip.setTextElideMode(Qt.TextElideMode.ElideRight)
    self.filmstrip.setVerticalScrollMode(QListWidget.ScrollMode.ScrollPerPixel)
    self.filmstrip.setVerticalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAsNeeded)
    self.filmstrip.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    self.filmstrip.setMouseTracking(True)
    self.filmstrip.setSelectionMode(QListWidget.SelectionMode.ExtendedSelection)
    self.filmstrip.setSelectionRectVisible(True)
    self._painted_thumbnail_rows: set[int] = set()
    self.filmstrip.currentRowChanged.connect(self._on_row_changed)
    self.filmstrip.itemClicked.connect(lambda _item: self._on_photo_selection_changed(show_single=True))
    self.filmstrip.itemSelectionChanged.connect(lambda: self._on_photo_selection_changed(show_single=True))
    self.filmstrip.itemDoubleClicked.connect(lambda _item: self._show_loupe())
    self.filmstrip.setContextMenuPolicy(Qt.ContextMenuPolicy.CustomContextMenu)
    self.filmstrip.customContextMenuRequested.connect(self._photo_context_menu)
    self._thumbnail_scroll_timer = QTimer(self)
    self._thumbnail_scroll_timer.setSingleShot(True)
    self._thumbnail_scroll_timer.setInterval(32)
    self._thumbnail_scroll_timer.timeout.connect(self._request_visible_thumbnails)
    self.filmstrip.verticalScrollBar().valueChanged.connect(self._schedule_visible_thumbnails)
    self._grid_resize_timer = QTimer(self)
    self._grid_resize_timer.setSingleShot(True)
    self._grid_resize_timer.setInterval(16)
    self._grid_resize_timer.timeout.connect(self._resize_grid)
    self.filmstrip.resized.connect(self._schedule_grid_resize)
    placeholder = QPixmap(185, 123)
    placeholder.fill(QColor("#1b1c20"))
    self.placeholder_icon = QIcon(placeholder)
    self.gallery_page = QWidget()
    gallery_layout = QVBoxLayout(self.gallery_page)
    gallery_layout.setContentsMargins(0, 0, 0, 0)
    gallery_layout.setSpacing(0)
    self.gallery_header = PhotoGridHeader(self.filmstrip)
    header_layout = QVBoxLayout(self.gallery_header)
    header_layout.setContentsMargins(0, 0, 0, 0)
    header_layout.setSpacing(0)
    self.folder_section = QWidget()
    self.folder_section.setSizePolicy(QSizePolicy.Policy.Preferred, QSizePolicy.Policy.Maximum)
    folder_page_layout = QVBoxLayout(self.folder_section)
    folder_page_layout.setContentsMargins(16, 6, 16, 14)
    folder_page_layout.setSpacing(4)
    folder_heading = QHBoxLayout()
    folder_heading.setSpacing(4)
    self.folder_children_heading = FolderSectionToggle()
    self.folder_children_heading.setChecked(False)
    folder_heading.addWidget(self.folder_children_heading)
    folder_heading.addStretch()
    folder_page_layout.addLayout(folder_heading)
    self.folder_cards_container = QWidget()
    self.folder_cards_layout = QGridLayout(self.folder_cards_container)
    self.folder_cards_layout.setContentsMargins(0, 0, 0, 0)
    self.folder_cards_layout.setHorizontalSpacing(16)
    self.folder_cards_layout.setVerticalSpacing(20)
    self.folder_cards_layout.setAlignment(Qt.AlignmentFlag.AlignTop | Qt.AlignmentFlag.AlignLeft)
    folder_page_layout.addWidget(self.folder_cards_container)
    self.folder_cards_container.hide()
    header_layout.addWidget(self.folder_section, 0, Qt.AlignmentFlag.AlignTop)
    self.folder_section.hide()
    self.folder_content_heading = label("", "folderContentHeading")
    header_layout.addWidget(self.folder_content_heading)
    self.folder_content_heading.hide()
    self.folder_children_heading.toggled.connect(self._toggle_folder_children)
    self.filmstrip.set_header(self.gallery_header)
    gallery_layout.addWidget(self.filmstrip, 1)
    self.folder_page = self.gallery_page
    self.center_stack.addWidget(self.gallery_page)
    loupe_page = QWidget()
    loupe_layout = QVBoxLayout(loupe_page)
    loupe_layout.setContentsMargins(0, 0, 0, 0)
    loupe_layout.setSpacing(8)
    self.preview_canvas = LoupeCanvas()
    self.preview_canvas.exitRequested.connect(self._show_grid)
    self.preview_canvas.zoomChanged.connect(self._sync_loupe_zoom)
    self.image_zoom_slider.valueChanged.connect(self._set_loupe_zoom)
    loupe_layout.addWidget(self.preview_canvas, 1)
    self.review_feedback = ReviewFeedback(self.preview_canvas)
    self.center_stack.addWidget(loupe_page)
    self.empty_page = QWidget()
    empty_layout = QVBoxLayout(self.empty_page)
    empty_layout.setContentsMargins(24, 24, 24, 24)
    empty_layout.setSpacing(0)
    empty_layout.setAlignment(Qt.AlignmentFlag.AlignCenter)
    self.empty_search_art = label("", "emptySearchArt")
    self.empty_search_art.setPixmap(QPixmap(asset_path("empty.search")).scaled(
        QSize(256, 144), Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation))
    empty_layout.addWidget(self.empty_search_art, 0, Qt.AlignmentFlag.AlignHCenter)
    self.empty_search_art.hide()
    self.empty_folder_art = EmptyFolderIllustration()
    empty_layout.addWidget(self.empty_folder_art, 0, Qt.AlignmentFlag.AlignHCenter)
    self.empty_folder_art.hide()
    empty_layout.addSpacing(24)
    self.empty_title = label("当前没有照片", "emptyFolderTitle")
    self.empty_title.setAlignment(Qt.AlignmentFlag.AlignCenter)
    self.empty_title.setMinimumHeight(24)
    self.empty_title.setWordWrap(True)
    empty_layout.addWidget(self.empty_title)
    empty_layout.addSpacing(8)
    self.empty_hint = label("可以导入照片文件夹，或切换筛选条件。", "emptyFolderHint")
    self.empty_hint.setAlignment(Qt.AlignmentFlag.AlignCenter)
    self.empty_hint.setWordWrap(False)
    self.empty_hint.setFixedSize(352, 18)
    empty_layout.addWidget(self.empty_hint, 0, Qt.AlignmentFlag.AlignHCenter)
    empty_layout.addSpacing(16)
    self.empty_actions = QWidget()
    empty_actions_layout = QHBoxLayout(self.empty_actions)
    empty_actions_layout.setContentsMargins(0, 0, 0, 0)
    empty_actions_layout.setSpacing(8)
    self.empty_link_button = QPushButton("关联本地文件夹")
    self.empty_link_button.setObjectName("emptyFolderAction")
    self.empty_link_button.setFixedSize(144, 32)
    self.empty_link_button.setCursor(Qt.CursorShape.PointingHandCursor)
    self.empty_link_button.setToolTip("将本地照片目录关联到当前文件夹")
    self.empty_link_button.clicked.connect(
        lambda: self.choose_project(bind_to_id=self.project_id))
    empty_actions_layout.addWidget(self.empty_link_button)
    self.empty_import_button = QPushButton("导入本地文件夹")
    self.empty_import_button.setObjectName("emptyFolderAction")
    self.empty_import_button.setFixedSize(144, 32)
    self.empty_import_button.setCursor(Qt.CursorShape.PointingHandCursor)
    self.empty_import_button.setToolTip("读取本地目录，在当前文件夹下建立同名子文件夹")
    self.empty_import_button.clicked.connect(
        lambda: self.choose_project(parent_id=self.project_id))
    empty_actions_layout.addWidget(self.empty_import_button)
    empty_layout.addWidget(self.empty_actions, 0, Qt.AlignmentFlag.AlignHCenter)
    self.empty_actions.hide()
    self.center_stack.addWidget(self.empty_page)
    viewer_layout.addWidget(self.center_stack, 1)
